def rows_of(ch):
    top, rows = GLYPHS[ch]
    width = len(rows[0])
    grid = ["." * width] * HEIGHT
    for i, row in enumerate(rows):
        grid[top + i] = row
    return grid


def to_java(path):
    chars = "".join(sorted(GLYPHS))
    out = ["package com.minimal.tvlauncher;", "",
           "// Generated by make_verb_font.py; edit that script, not this file.",
           "final class VerbFont {", "",
           "    static final int HEIGHT = %d;" % HEIGHT,
           "    static final String CHARS = \"%s\";" % chars.replace("\\", "\\\\").replace('"', '\\"'),
           "",
           "    // One string per row of each glyph, '#' = pixel.",
           "    static final String[][] GLYPHS = {"]
    for ch in chars:
        out.append("            {" + ", ".join('"%s"' % r for r in rows_of(ch)) + "},")
    out += ["    };", "", "    private VerbFont() {", "    }", "}"]
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def render(text, bold=False):
    """Returns (width, set of (x, y) pixels) — mirrors ScummView's drawing."""
    x, pixels = 0, set()
    for ch in text:
        if ch not in GLYPHS:
            ch = " "
        grid = rows_of(ch)
        for y, row in enumerate(grid):
            for i, c in enumerate(row):
                if c == "#":
                    pixels.add((x + i, y))
                    if bold:
                        pixels.add((x + i + 1, y))
        x += len(grid[0]) + (2 if bold else 1)
    return x, pixels


if __name__ == "__main__":
    to_java(sys.argv[1])
    if len(sys.argv) > 2:
        from PIL import Image
        words = ["Open", "Wi-Fi", "Picture", "Look at", "Bluetooth", "Apps", "Close", "Sound", "Settings",
                 "ABCDEFGHIJKLM", "NOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz"]
        img = Image.new("RGB", (240, 14 * len(words) + 4), (0, 0, 0))
        for n, w in enumerate(words):
            _, px = render(w)
            for (x, y) in px:
                img.putpixel((4 + x + 1, 3 + n * 14 + y + 1), (0x4c, 0x00, 0x4c))
            for (x, y) in px:
                img.putpixel((4 + x, 3 + n * 14 + y), (0xa8, 0x40, 0xa8))
        img.resize((img.width * 5, img.height * 5), Image.NEAREST).save(sys.argv[2])
